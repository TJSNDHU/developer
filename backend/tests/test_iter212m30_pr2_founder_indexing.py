@pytest.mark.asyncio
async def test_confirm_flips_status_and_kicks_runner():
    from routers import founder_offer
    db = _SingletonFakeMongo()
    db.claims["c1"] = {
        "claim_id": "c1", "user_id": "u1", "repo_id": "p1",
        "fix_status": "preview", "site_url": "",
        "created_at": datetime.now(timezone.utc),
    }

    started = asyncio.Event()

    async def fake_real_fix(**kwargs):
        started.set()

    with patch("routers.founder_offer.get_db", return_value=db), \
         patch("routers.founder_offer.current_dev",
               new=AsyncMock(return_value={"user_id": "u1"})), \
         patch("routers.founder_offer._run_real_fix",
               side_effect=fake_real_fix) as runner:
        r = await founder_offer.confirm_offer(
            founder_offer._ConfirmBody(claim_id="c1"),
            authorization="Bearer x",
        )
        # Give the create_task a chance to run.
        await asyncio.wait_for(started.wait(), timeout=2.0)

    assert r["success"] is True
    assert r["fix_status"] == "running"
    assert db.claims["c1"]["fix_status"] == "running"
    runner.assert_called_once()


