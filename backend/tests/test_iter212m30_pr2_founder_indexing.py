# 3. Founder offer — atomic spot decrement
# ════════════════════════════════════════════════════════════════════

class _SingletonFakeMongo:
    """A microscopic Mongo stand-in that supports the operations the
    founder_offer router actually uses (find_one, find_one_and_update
    with $inc + $expr, update_one, insert_one). Single-threaded so we
    can model the "atomic" guarantee with a regular dict."""

    def __init__(self):
        # founder_offer singleton
        self._offer = None
        self.claims: dict[str, dict] = {}        # claim_id → doc
        self.users: dict[str, dict] = {}

    # ── helpers ────────────────────────────────────────────────
    def reset(self):
        self._offer = None
        self.claims.clear()

    # ── founder_offer collection ───────────────────────────────
    class _Offer:
        def __init__(self, outer): self._o = outer
        async def find_one(self, q):
            return dict(self._o._offer) if self._o._offer else None
        async def find_one_and_update(self, q, update, upsert=False, return_document=False):
            o = self._o
            if o._offer is None:
                if "$setOnInsert" in update and upsert:
                    o._offer = dict(update["$setOnInsert"])
                else:
                    return None
            if "$expr" in q:
                if not (o._offer["spots_claimed"] < o._offer["total_spots"]
                        and o._offer.get("is_active", True)):
                    return None
            if "$inc" in update:
                for k, v in update["$inc"].items():
                    o._offer[k] = o._offer.get(k, 0) + v
            if "$set" in update:
                o._offer.update(update["$set"])
            return dict(o._offer)
        async def update_one(self, q, update):
            o = self._o
            if o._offer is None:
                return type("R", (), {"matched_count": 0})()
            if "spots_claimed" in q and isinstance(q["spots_claimed"], dict):
                if not (o._offer["spots_claimed"] > q["spots_claimed"].get("$gt", -1)):
                    return type("R", (), {"matched_count": 0})()
            if "$inc" in update:
                for k, v in update["$inc"].items():
                    o._offer[k] = o._offer.get(k, 0) + v
            return type("R", (), {"matched_count": 1})()

    # ── user_seo_claims collection ─────────────────────────────
    class _Claims:
        def __init__(self, outer): self._o = outer
        def find(self, q):
            outer = self._o
            matches = [
                v for v in outer.claims.values()
                if all(_match(v, k, val) for k, val in q.items())
            ]
            class _Cursor:
                def __init__(self, items): self.items = items
                def sort(self, *_args): return self
                async def to_list(self, length): return list(self.items)[:length]
            return _Cursor(matches)
        async def find_one(self, q):
            for v in self._o.claims.values():
                if all(_match(v, k, val) for k, val in q.items()):
                    return dict(v)
            return None
        async def find_one_and_update(self, q, update, return_document=False):
            target = None
            for v in self._o.claims.values():
                if all(_match(v, k, val) for k, val in q.items()):
                    target = v
                    break
            if target is None:
                return None
            if "$set" in update:
                target.update(update["$set"])
            return dict(target)
        async def insert_one(self, doc):
            self._o.claims[doc["claim_id"]] = dict(doc)
            return type("R", (), {"inserted_id": doc["claim_id"]})()
        async def update_one(self, q, update):
            target = None
            for v in self._o.claims.values():
                if all(_match(v, k, val) for k, val in q.items()):
                    target = v
                    break
            if target is None:
                return type("R", (), {"matched_count": 0})()
            if "$set" in update:
                target.update(update["$set"])
            return type("R", (), {"matched_count": 1})()
        async def create_index(self, *a, **k):
            return None

    # ── dev_users ──────────────────────────────────────────────
    class _Users:
        def __init__(self, outer): self._o = outer
        async def find_one(self, q, projection=None):
            uid = q.get("user_id")
            return self._o.users.get(uid)
        async def insert_one(self, doc):
            self._o.users[doc["user_id"]] = dict(doc)

    @property
    def founder_offer(self): return self._Offer(self)
    @property
    def user_seo_claims(self): return self._Claims(self)
    @property
    def dev_users(self): return self._Users(self)


def _match(doc, key, val):
    if isinstance(val, dict):
        if "$ne" in val:
            return doc.get(key) != val["$ne"]
        if "$gt" in val:
            return (doc.get(key) or 0) > val["$gt"]
    return doc.get(key) == val


